#!/usr/bin/env node
// uspace-ui-gen-api: generates a web/'s API types from its system's
// api/openapi.yaml with the openapi-typescript this package pins, so every
// web/ generates the same way (docs/PLAN.md §14 Q14; spec 00 §6.2).
//
//   uspace-ui-gen-api <openapi.yaml> <out.d.ts>           write the types
//   uspace-ui-gen-api <openapi.yaml> <out.d.ts> --check   exit 1 if <out> is not current
//
// The first line of the output names this tool, its version, the
// generator's version and the SHA-256 of the input; the
// `no-hand-written-api-types` lint rule recognises it (WP-0).
//
// Exit codes: 0 written or current; 1 --check found the output missing or
// different; 2 usage error or the input could not be generated from.
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString, COMMENT_HEADER } from "openapi-typescript";

const require = createRequire(import.meta.url);
const KIT_VERSION = require("../package.json").version;
const GENERATOR_VERSION = require("openapi-typescript/package.json").version;

const USAGE = "usage: uspace-ui-gen-api <openapi.yaml> <out.d.ts> [--check]";

/** The header line; `@generated by uspace-ui-gen-api` is the lint marker. */
export function headerLine(inputBytes) {
  const sha256 = createHash("sha256").update(inputBytes).digest("hex");
  return `// @generated by uspace-ui-gen-api ${KIT_VERSION} (openapi-typescript ${GENERATOR_VERSION}) from ${sha256}; do not edit`;
}

/** The full output for one OpenAPI file, header first. */
export async function generate(inputPath) {
  const bytes = readFileSync(inputPath);
  const ast = await openapiTS(pathToFileURL(resolve(inputPath)));
  return `${headerLine(bytes)}\n${COMMENT_HEADER}${astToString(ast)}`;
}

async function main(argv) {
  const check = argv.includes("--check");
  const args = argv.filter((a) => a !== "--check");
  if (args.length !== 2 || args.some((a) => a.startsWith("-"))) {
    console.error(USAGE);
    return 2;
  }
  const [input, output] = args;
  if (!existsSync(input)) {
    console.error(`uspace-ui-gen-api: ${input} does not exist`);
    return 2;
  }
  let text;
  try {
    text = await generate(input);
  } catch (err) {
    console.error(
      `uspace-ui-gen-api: cannot generate from ${input}: ${err instanceof Error ? err.message : String(err)}`,
    );
    return 2;
  }
  if (check) {
    if (!existsSync(output)) {
      console.error(
        `uspace-ui-gen-api: ${output} is missing; run uspace-ui-gen-api ${input} ${output}`,
      );
      return 1;
    }
    if (readFileSync(output, "utf8") !== text) {
      console.error(
        `uspace-ui-gen-api: ${output} is not what ${input} generates; run uspace-ui-gen-api ${input} ${output} and commit the result`,
      );
      return 1;
    }
    console.log(`uspace-ui-gen-api: ${output} is current`);
    return 0;
  }
  mkdirSync(dirname(resolve(output)), { recursive: true });
  writeFileSync(output, text);
  console.log(`uspace-ui-gen-api: wrote ${output}`);
  return 0;
}

// Run as the bin, not when a test imports the functions above. A package
// manager reaches the bin through a link, so both sides are real paths.
function isMain() {
  const invoked = process.argv[1];
  if (invoked === undefined || !existsSync(invoked)) return false;
  return realpathSync(invoked) === realpathSync(fileURLToPath(import.meta.url));
}

if (isMain()) {
  process.exitCode = await main(process.argv.slice(2));
}
