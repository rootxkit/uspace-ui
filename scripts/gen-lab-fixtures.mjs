// Writes src/test/labExamples.generated.ts from the lab-derived fixtures
// in src/test/fixtures/ (WP-14), so `fixtures({ source: "lab" })`
// works wherever the `/test` entry runs (node, jsdom, a browser) without
// reading files. The JSON files stay the reviewed copy (checksums, online
// diff); this module is derived from them and checked to be current.
//
//   node scripts/gen-lab-fixtures.mjs           write the module
//   node scripts/gen-lab-fixtures.mjs --check   exit 1 if it is stale
//
// From the ED-318 round-trip vector only the documents a parse accepts
// are taken (the refused ones are the lab's tests of a parser, not
// shapes a console renders).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

export const FIXTURES_DIR = "src/test/fixtures";
export const MODULE = "src/test/labExamples.generated.ts";

function files(dir) {
  return readdirSync(dir)
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? files(p) : [p];
    })
    .filter((p) => p.endsWith(".json"))
    .sort();
}

/** The pinned lab commit, from the fixtures' VERSION file. */
export function labCommitOf(version) {
  const m = /^uspace_lab_commit\s*=\s*([0-9a-f]{40})\s*$/m.exec(version);
  if (m === null) throw new Error("gen-lab-fixtures: no uspace_lab_commit");
  return m[1];
}

export function render(root = ".") {
  const dir = join(root, FIXTURES_DIR);
  const commit = labCommitOf(readFileSync(join(dir, "VERSION"), "utf8"));
  const examples = {};
  let ed318 = [];
  for (const file of files(dir)) {
    const key = relative(dir, file).replace(/\\/g, "/");
    const value = JSON.parse(readFileSync(file, "utf8"));
    if (key === "lab/vectors/ed318_roundtrip.json") {
      ed318 = value.cases
        .filter(
          (c) => c.input?.kind === "parse" && c.expected?.accepted === true,
        )
        .map((c) => ({ name: c.name, document: c.input.document }));
    } else {
      examples[key] = value;
    }
  }
  return [
    "// Generated by scripts/gen-lab-fixtures.mjs from src/test/fixtures/",
    "// (pinned in its VERSION); never edited by hand. Run",
    "// scripts/sync-fixtures.sh to move a pin.",
    "",
    "/** The uspace-lab commit the common examples were copied at. */",
    `export const LAB_COMMIT = ${JSON.stringify(commit)};`,
    "",
    "/** Every vendored example, by its path under src/test/fixtures/. */",
    `export const LAB_EXAMPLES: Readonly<Record<string, unknown>> = ${JSON.stringify(examples, null, 2)};`,
    "",
    "/** The ED-318 documents the lab's round-trip vector accepts. */",
    `export const ED318_ACCEPTED: readonly { name: string; document: unknown }[] = ${JSON.stringify(ed318, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(MODULE, "utf8");
    } catch {
      current = "";
    }
    if (current !== text) {
      console.error(
        `gen-lab-fixtures: ${MODULE} is stale; run node scripts/gen-lab-fixtures.mjs`,
      );
      process.exitCode = 1;
    } else {
      console.log(`gen-lab-fixtures: ${MODULE} is current`);
    }
  } else {
    writeFileSync(MODULE, text);
    console.log(`gen-lab-fixtures: wrote ${MODULE}`);
  }
}
